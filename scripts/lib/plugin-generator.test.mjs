import { cpSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import {
  GeneratorError,
  MARKETPLACE_PATH,
  PLUGIN_DIR,
  buildPlugin,
  findStaleFiles,
  listFiles,
  parseFrontmatter,
  writePlugin,
} from './plugin-generator.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const fixture = join(here, '..', 'test', 'fixtures', 'plugin-agents');
const cli = join(here, '..', 'generate-plugin.mjs');

let root;
beforeEach(() => {
  root = mkdtempSync(join(tmpdir(), 'race-plugin-test-'));
  cpSync(fixture, join(root, 'agents'), { recursive: true });
});
afterEach(() => {
  rmSync(root, { recursive: true, force: true });
});

const agents = () => join(root, 'agents');
const edit = (relative, content) => {
  mkdirSync(dirname(join(agents(), relative)), { recursive: true });
  writeFileSync(join(agents(), relative), content);
};
const failure = (fn) => {
  try {
    fn();
  } catch (error) {
    expect(error).toBeInstanceOf(GeneratorError);
    return error.message;
  }
  throw new Error('expected a GeneratorError');
};

describe('buildPlugin', () => {
  it('produces the expected sorted tree', () => {
    const tree = buildPlugin(agents());
    expect([...tree.keys()]).toEqual([
      '.claude-plugin/marketplace.json',
      `${PLUGIN_DIR}/.claude-plugin/plugin.json`,
      `${PLUGIN_DIR}/.mcp.json`,
      `${PLUGIN_DIR}/GENERATED.md`,
      `${PLUGIN_DIR}/agents/narrator.md`,
      `${PLUGIN_DIR}/bin/race-server.mjs`,
      `${PLUGIN_DIR}/commands/new-run.md`,
      `${PLUGIN_DIR}/hooks/guard.mjs`,
      `${PLUGIN_DIR}/hooks/hooks.json`,
      `${PLUGIN_DIR}/skills/investigate/SKILL.md`,
      `${PLUGIN_DIR}/skills/investigate/reference.md`,
    ]);
  });

  it('keeps frontmatter first and marks markdown as generated', () => {
    const skill = buildPlugin(agents()).get(`${PLUGIN_DIR}/skills/investigate/SKILL.md`);
    expect(skill).toBe(
      '---\nname: investigate\ndescription: Fixture skill.\n---\n<!-- Generated by scripts/generate-plugin.mjs from agents/. Do not edit: change agents/ and run `npm run generate`. -->\n\n# Investigate\n\nBody.\n',
    );
  });

  it('declares the MCP server through a launcher inside the plugin, never a path that leaves it', () => {
    const mcp = JSON.parse(buildPlugin(agents()).get(`${PLUGIN_DIR}/.mcp.json`));
    expect(mcp).toEqual({
      mcpServers: {
        'the-race': { command: 'node', args: ['${CLAUDE_PLUGIN_ROOT}/bin/race-server.mjs'] },
      },
    });
  });

  it('lists the plugin in the marketplace with a relative source', () => {
    const marketplace = JSON.parse(buildPlugin(agents()).get(MARKETPLACE_PATH));
    expect(marketplace.name).toBe('the-race');
    expect(marketplace.owner).toEqual({ name: 'The RACE Authors' });
    expect(marketplace.plugins).toEqual([
      { name: 'the-race', source: './plugins/the-race', description: 'Fixture plugin.', version: '0.0.1' },
    ]);
  });

  it('wraps a bare hooks map and passes a wrapped one through', () => {
    const wrapped = JSON.parse(buildPlugin(agents()).get(`${PLUGIN_DIR}/hooks/hooks.json`));
    expect(wrapped.hooks.PreToolUse[0].matcher).toBe('Read');

    edit('hooks/hooks.json', JSON.stringify({ hooks: { SessionStart: [] } }));
    const again = JSON.parse(buildPlugin(agents()).get(`${PLUGIN_DIR}/hooks/hooks.json`));
    expect(again).toEqual({ hooks: { SessionStart: [] } });
  });

  it('works without optional folders and normalizes CRLF', () => {
    rmSync(join(agents(), 'hooks'), { recursive: true });
    rmSync(join(agents(), 'commands'), { recursive: true });
    rmSync(join(agents(), 'subagents'), { recursive: true });
    edit('skills/investigate/reference.md', 'a\r\nb\r\n');
    const tree = buildPlugin(agents());
    expect(tree.get(`${PLUGIN_DIR}/skills/investigate/reference.md`)).toBe('a\nb\n');
    expect([...tree.keys()].some((path) => path.includes('/hooks/'))).toBe(false);
  });

  it('is deterministic', () => {
    expect([...buildPlugin(agents())]).toEqual([...buildPlugin(agents())]);
  });
});

describe('errors', () => {
  it('names a missing agents directory', () => {
    expect(failure(() => buildPlugin(join(root, 'nope')))).toContain('agents/ is required');
  });

  it('names a missing plugin.json', () => {
    rmSync(join(agents(), 'plugin.json'));
    expect(failure(() => buildPlugin(agents()))).toContain('agents/plugin.json is required');
  });

  it('rejects broken or incomplete plugin.json', () => {
    edit('plugin.json', '{oops');
    expect(failure(() => buildPlugin(agents()))).toContain('not valid JSON');
    edit('plugin.json', '[]');
    expect(failure(() => buildPlugin(agents()))).toContain('must be a JSON object');
    edit('plugin.json', JSON.stringify({ name: 'the-race', version: '1' }));
    expect(failure(() => buildPlugin(agents()))).toContain('"description"');
    const base = JSON.parse(readFileSync(join(fixture, 'plugin.json'), 'utf8'));
    edit('plugin.json', JSON.stringify({ ...base, name: 'The Race' }));
    expect(failure(() => buildPlugin(agents()))).toContain('kebab-case');
    edit('plugin.json', JSON.stringify({ ...base, author: 'me' }));
    expect(failure(() => buildPlugin(agents()))).toContain('"author"');
  });

  it('requires skills', () => {
    rmSync(join(agents(), 'skills'), { recursive: true });
    expect(failure(() => buildPlugin(agents()))).toContain('agents/skills/ is required');
    mkdirSync(join(agents(), 'skills'));
    expect(failure(() => buildPlugin(agents()))).toContain('at least one skill');
    mkdirSync(join(agents(), 'skills', 'empty'));
    expect(failure(() => buildPlugin(agents()))).toContain('agents/skills/empty/SKILL.md is required');
  });

  it('rejects bad frontmatter with the file and the problem', () => {
    edit('skills/investigate/SKILL.md', 'no frontmatter\n');
    expect(failure(() => buildPlugin(agents()))).toContain('must start with "---"');
    edit('skills/investigate/SKILL.md', '---\nname: investigate\n');
    expect(failure(() => buildPlugin(agents()))).toContain('not closed');
    edit('skills/investigate/SKILL.md', '---\nname: investigate\nnot a pair\n---\n');
    expect(failure(() => buildPlugin(agents()))).toContain('bad frontmatter on line 3');
    edit('skills/investigate/SKILL.md', '---\nname: a\nname: b\n---\n');
    expect(failure(() => buildPlugin(agents()))).toContain('duplicate frontmatter key "name"');
    edit('skills/investigate/SKILL.md', '---\nname: investigate\n---\n');
    expect(failure(() => buildPlugin(agents()))).toContain('missing required "description"');
    edit('skills/investigate/SKILL.md', '---\nname: other\ndescription: x\n---\n');
    expect(failure(() => buildPlugin(agents()))).toContain('must equal the directory name');
  });

  it('checks subagents and commands', () => {
    edit('subagents/narrator.md', '---\nname: someone\ndescription: x\n---\n');
    expect(failure(() => buildPlugin(agents()))).toContain('must equal the file name');
    edit('subagents/narrator.md', '---\nname: narrator\ndescription: x\n---\n');
    edit('commands/notes.txt', 'x');
    expect(failure(() => buildPlugin(agents()))).toContain('only .md files');
    rmSync(join(agents(), 'commands', 'notes.txt'));
    edit('commands/new-run.md', '---\n---\n');
    expect(failure(() => buildPlugin(agents()))).toContain('missing required "description"');
  });

  it('checks hooks', () => {
    rmSync(join(agents(), 'hooks', 'hooks.json'));
    expect(failure(() => buildPlugin(agents()))).toContain('hooks.json is required');
    edit('hooks/hooks.json', '{oops');
    expect(failure(() => buildPlugin(agents()))).toContain('not valid JSON');
    edit('hooks/hooks.json', '[]');
    expect(failure(() => buildPlugin(agents()))).toContain('must be a JSON object');
    edit('hooks/hooks.json', '{"hooks": []}');
    expect(failure(() => buildPlugin(agents()))).toContain('keyed by event name');
    edit(
      'hooks/hooks.json',
      JSON.stringify({ PreToolUse: [{ hooks: [{ command: '${CLAUDE_PLUGIN_ROOT}/hooks/gone.mjs' }] }] }),
    );
    expect(failure(() => buildPlugin(agents()))).toContain('hooks/gone.mjs');
  });
});

describe('parseFrontmatter', () => {
  it('strips quotes, comments and blank lines', () => {
    const { data, body } = parseFrontmatter('---\n# c\n\ndescription: "Quoted: yes"\n---\nBody', 'x');
    expect(data).toEqual({ description: 'Quoted: yes' });
    expect(body).toBe('Body');
  });
});

describe('findStaleFiles and writePlugin', () => {
  it('writes a tree that then checks clean, and lists exactly the files', () => {
    const tree = buildPlugin(agents());
    writePlugin(root, tree);
    expect(findStaleFiles(root, tree)).toEqual([]);
    expect(listFiles(join(root, PLUGIN_DIR))).toHaveLength(tree.size - 1);
  });

  it('reports missing, out-of-date and unexpected files', () => {
    const tree = buildPlugin(agents());
    writePlugin(root, tree);
    rmSync(join(root, PLUGIN_DIR, '.mcp.json'));
    writeFileSync(join(root, PLUGIN_DIR, 'GENERATED.md'), 'hand edit');
    writeFileSync(join(root, PLUGIN_DIR, 'stray.txt'), 'x');
    expect(findStaleFiles(root, tree)).toEqual([
      `missing: ${PLUGIN_DIR}/.mcp.json`,
      `out of date: ${PLUGIN_DIR}/GENERATED.md`,
      `unexpected: ${PLUGIN_DIR}/stray.txt`,
    ]);
  });

  it('reports everything missing when nothing was generated', () => {
    const tree = buildPlugin(agents());
    expect(findStaleFiles(root, tree)).toHaveLength(tree.size);
  });

  it('removes files that agents/ no longer yields when regenerating', () => {
    writePlugin(root, buildPlugin(agents()));
    rmSync(join(agents(), 'commands'), { recursive: true });
    writePlugin(root, buildPlugin(agents()));
    expect(listFiles(join(root, PLUGIN_DIR))).not.toContain('commands/new-run.md');
  });
});

describe('generate-plugin CLI', () => {
  const run = (...args) => {
    try {
      const stdout = execFileSync(process.execPath, [cli, '--root', root, ...args], {
        encoding: 'utf8',
        stdio: 'pipe',
      });
      return { code: 0, out: stdout };
    } catch (error) {
      return { code: error.status, out: String(error.stdout) + String(error.stderr) };
    }
  };

  it('generates, then passes the check, then fails it with a clear message once stale', () => {
    expect(run().code).toBe(0);
    expect(run('--check')).toMatchObject({ code: 0 });
    writeFileSync(join(agents(), 'skills', 'investigate', 'reference.md'), 'changed\n');
    const stale = run('--check');
    expect(stale.code).toBe(1);
    expect(stale.out).toContain('The generated plugin is stale');
    expect(stale.out).toContain('out of date: plugins/the-race/skills/investigate/reference.md');
    expect(stale.out).toContain('npm run generate');
  });

  it('explains a generation failure instead of crashing', () => {
    rmSync(join(agents(), 'plugin.json'));
    const result = run();
    expect(result.code).toBe(1);
    expect(result.out).toContain('Cannot generate the plugin: agents/plugin.json is required');
  });

  it('has nothing to check before agents/ exists', () => {
    rmSync(agents(), { recursive: true });
    expect(run('--check').out).toContain('nothing to check');
  });

  it('fails the check when agents/ is gone but the tree remains', () => {
    run();
    rmSync(agents(), { recursive: true });
    expect(run('--check').code).toBe(1);
  });
});
