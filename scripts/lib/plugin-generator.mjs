// Builds the Claude Code plugin tree from the canonical `agents/` directory. Pure with respect to the
// output: it returns a map of repo-relative POSIX paths to file contents and writes nothing, so the same
// result serves both `npm run generate` (write it) and `npm run lint:generated` (compare it).
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

export const PLUGIN_DIR = 'plugins/the-race';
export const MARKETPLACE_PATH = '.claude-plugin/marketplace.json';

// The MCP server is built inside this repository (packages/mcp) and the plugin sits two levels below the
// repository root. A path in .mcp.json that climbs out of the plugin directory is not something Claude Code
// documents as supported, so the server is started through a small launcher INSIDE the plugin, which finds
// the build relative to its own file. A relative marketplace source is loaded in place, which is what
// makes that work; a copied install would need the server bundled into the plugin.
export const MCP_LAUNCHER = 'bin/race-server.mjs';
export const MCP_SERVER_ARGS = ['${CLAUDE_PLUGIN_ROOT}/' + MCP_LAUNCHER];

const LAUNCHER_SOURCE = `// Generated by scripts/generate-plugin.mjs from agents/. Do not edit.
// Starts the game's MCP server from the repository checkout this plugin sits in.
import { existsSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

const entry = fileURLToPath(new URL('../../../packages/mcp/dist/main.js', import.meta.url));
if (!existsSync(entry)) {
  console.error('the RACE server is not built: run "npm ci" and "npm run build" in the repository, then start a new session.');
  process.exit(1);
}
await import(pathToFileURL(entry).href);
`;
export const MCP_SERVER_NAME = 'the-race';

// The folder the player picks at the first start (a `userConfig` option of the plugin) reaches the server as
// an environment variable; a hook gets the same answer as CLAUDE_PLUGIN_OPTION_GAME_FOLDER by itself. The
// reference is only valid when the manifest declares the option, so a manifest without it gets no `env`.
export const GAME_FOLDER_OPTION = 'game_folder';
export const GAME_FOLDER_ENV = 'RACE_GAME_FOLDER';

function mcpServer(meta) {
  const server = { command: 'node', args: MCP_SERVER_ARGS };
  if (meta.userConfig?.[GAME_FOLDER_OPTION] !== undefined) {
    server.env = { [GAME_FOLDER_ENV]: '${user_config.' + GAME_FOLDER_OPTION + '}' };
  }
  return server;
}

const KEBAB = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const GENERATED_NOTE =
  'Generated by scripts/generate-plugin.mjs from agents/. Do not edit: change agents/ and run `npm run generate`.';

export class GeneratorError extends Error {
  constructor(message) {
    super(message);
    this.name = 'GeneratorError';
  }
}

function normalize(text) {
  return text.replace(/\r\n/g, '\n');
}

function readText(path) {
  return normalize(readFileSync(path, 'utf8'));
}

function json(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

/** Every file under `dir`, as sorted POSIX paths relative to it. */
export function listFiles(dir) {
  const found = [];
  const walk = (current, prefix) => {
    for (const entry of readdirSync(current, { withFileTypes: true })) {
      const relative = prefix ? `${prefix}/${entry.name}` : entry.name;
      if (entry.isDirectory()) walk(join(current, entry.name), relative);
      else found.push(relative);
    }
  };
  walk(dir, '');
  return found.sort();
}

function listDirs(dir) {
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
}

/** Parses the flat `key: value` frontmatter these files use; anything richer is rejected loudly. */
export function parseFrontmatter(text, label) {
  const lines = normalize(text).split('\n');
  if (lines[0] !== '---') throw new GeneratorError(`${label}: frontmatter must start with "---" on line 1`);
  const end = lines.indexOf('---', 1);
  if (end === -1) throw new GeneratorError(`${label}: frontmatter is not closed with "---"`);
  const data = {};
  for (const [index, line] of lines.slice(1, end).entries()) {
    if (line.trim() === '' || line.startsWith('#')) continue;
    const match = /^([A-Za-z][\w-]*):[ \t]*(.*)$/.exec(line);
    if (!match) throw new GeneratorError(`${label}: bad frontmatter on line ${index + 2}: "${line}"`);
    const key = match[1];
    if (key in data) throw new GeneratorError(`${label}: duplicate frontmatter key "${key}"`);
    data[key] = match[2].replace(/^(["'])(.*)\1$/, '$2');
  }
  return { data, body: lines.slice(end + 1).join('\n'), frontmatterLines: lines.slice(0, end + 1) };
}

function requireFields(data, fields, label) {
  for (const field of fields) {
    if (!data[field]) throw new GeneratorError(`${label}: frontmatter is missing required "${field}"`);
  }
}

// Frontmatter must stay the first thing in the file, so the marker goes right after it.
function withMarker(text, label) {
  const { frontmatterLines, body } = parseFrontmatter(text, label);
  return `${frontmatterLines.join('\n')}\n<!-- ${GENERATED_NOTE} -->\n${body.replace(/^\n+/, '\n')}`;
}

function readPluginMeta(agentsDir) {
  const path = join(agentsDir, 'plugin.json');
  if (!existsSync(path)) throw new GeneratorError('agents/plugin.json is required but missing');
  let meta;
  try {
    meta = JSON.parse(readText(path));
  } catch (error) {
    throw new GeneratorError(`agents/plugin.json is not valid JSON: ${error.message}`);
  }
  if (typeof meta !== 'object' || meta === null || Array.isArray(meta)) {
    throw new GeneratorError('agents/plugin.json must be a JSON object');
  }
  for (const field of ['name', 'version', 'description', 'license']) {
    if (typeof meta[field] !== 'string' || meta[field] === '') {
      throw new GeneratorError(`agents/plugin.json: "${field}" must be a non-empty string`);
    }
  }
  if (!KEBAB.test(meta.name)) throw new GeneratorError('agents/plugin.json: "name" must be kebab-case');
  const author = meta.author;
  if (typeof author !== 'object' || author === null || typeof author.name !== 'string' || !author.name) {
    throw new GeneratorError('agents/plugin.json: "author" must be an object with a "name"');
  }
  return meta;
}

function collectSkills(agentsDir, out) {
  const root = join(agentsDir, 'skills');
  if (!existsSync(root)) throw new GeneratorError('agents/skills/ is required but missing');
  const names = listDirs(root);
  if (names.length === 0) throw new GeneratorError('agents/skills/ must hold at least one skill');
  for (const name of names) {
    const skillFile = join(root, name, 'SKILL.md');
    if (!existsSync(skillFile))
      throw new GeneratorError(`agents/skills/${name}/SKILL.md is required but missing`);
    for (const file of listFiles(join(root, name))) {
      const source = join(root, name, file);
      if (file === 'SKILL.md') {
        const label = `agents/skills/${name}/SKILL.md`;
        const text = readText(source);
        const { data } = parseFrontmatter(text, label);
        requireFields(data, ['name', 'description'], label);
        if (data.name !== name) {
          throw new GeneratorError(
            `${label}: frontmatter name "${data.name}" must equal the directory name "${name}"`,
          );
        }
        out.set(`${PLUGIN_DIR}/skills/${name}/SKILL.md`, withMarker(text, label));
      } else {
        out.set(`${PLUGIN_DIR}/skills/${name}/${file}`, readText(source));
      }
    }
  }
}

function collectMarkdownDir(agentsDir, folder, requiredFields, out) {
  const root = join(agentsDir, folder);
  if (!existsSync(root)) return;
  for (const file of listFiles(root)) {
    const label = `agents/${folder}/${file}`;
    if (!file.endsWith('.md'))
      throw new GeneratorError(`${label}: only .md files belong in agents/${folder}/`);
    const text = readText(join(root, file));
    const { data } = parseFrontmatter(text, label);
    requireFields(data, requiredFields, label);
    if (folder === 'subagents' && data.name !== file.slice(0, -3)) {
      throw new GeneratorError(`${label}: frontmatter name "${data.name}" must equal the file name`);
    }
    // Claude Code calls the subagent folder `agents/`.
    const target = folder === 'subagents' ? 'agents' : folder;
    out.set(`${PLUGIN_DIR}/${target}/${file}`, withMarker(text, label));
  }
}

// hooks.json may be the wrapped form Claude Code reads ({"hooks": {...}}) or the bare event map.
function collectHooks(agentsDir, out) {
  const root = join(agentsDir, 'hooks');
  if (!existsSync(root)) return;
  const files = listFiles(root);
  const configPath = join(root, 'hooks.json');
  if (!files.includes('hooks.json'))
    throw new GeneratorError('agents/hooks/hooks.json is required when agents/hooks/ exists');
  let config;
  try {
    config = JSON.parse(readText(configPath));
  } catch (error) {
    throw new GeneratorError(`agents/hooks/hooks.json is not valid JSON: ${error.message}`);
  }
  if (typeof config !== 'object' || config === null || Array.isArray(config)) {
    throw new GeneratorError('agents/hooks/hooks.json must be a JSON object');
  }
  const wrapped = 'hooks' in config ? config : { hooks: config };
  if (typeof wrapped.hooks !== 'object' || wrapped.hooks === null || Array.isArray(wrapped.hooks)) {
    throw new GeneratorError('agents/hooks/hooks.json: "hooks" must be an object keyed by event name');
  }
  // A hook that points at a script that was never shipped fails silently at runtime; fail here instead.
  for (const match of JSON.stringify(wrapped).matchAll(/\$\{CLAUDE_PLUGIN_ROOT\}\/hooks\/([\w./-]+)/g)) {
    const script = match[1];
    if (!files.includes(script)) {
      throw new GeneratorError(
        `agents/hooks/hooks.json refers to hooks/${script}, which is not in agents/hooks/`,
      );
    }
  }
  // A hooks module that was never shipped is not loaded, and nothing says so: fail here instead.
  for (const module of Array.isArray(wrapped.modules) ? wrapped.modules : []) {
    const script = String(module).replace(/^\.\//, '');
    if (!files.includes(script)) {
      throw new GeneratorError(
        `agents/hooks/hooks.json lists the module ${module}, which is not in agents/hooks/`,
      );
    }
  }
  out.set(`${PLUGIN_DIR}/hooks/hooks.json`, json(wrapped));
  for (const file of files) {
    if (file !== 'hooks.json') out.set(`${PLUGIN_DIR}/hooks/${file}`, readText(join(root, file)));
  }
}

// The contract of the values a hooks module keeps in the session, named by `types` in plugin.json.
function collectTypes(agentsDir, meta, out) {
  const root = join(agentsDir, 'types');
  if (!existsSync(root)) {
    if (meta.types !== undefined) {
      throw new GeneratorError('agents/plugin.json names "types", but agents/types/ is missing');
    }
    return;
  }
  for (const file of listFiles(root)) out.set(`${PLUGIN_DIR}/types/${file}`, readText(join(root, file)));
  const named = typeof meta.types === 'string' ? meta.types.replace(/^\.\//, '') : undefined;
  if (named === undefined || !out.has(`${PLUGIN_DIR}/${named}`)) {
    throw new GeneratorError('agents/plugin.json: "types" must name a file in agents/types/');
  }
}

/** The whole generated tree: repo-relative POSIX path -> file content. */
export function buildPlugin(agentsDir) {
  if (!existsSync(agentsDir) || !statSync(agentsDir).isDirectory()) {
    throw new GeneratorError('agents/ is required but missing');
  }
  const meta = readPluginMeta(agentsDir);
  const out = new Map();
  out.set(`${PLUGIN_DIR}/.claude-plugin/plugin.json`, json(meta));
  collectSkills(agentsDir, out);
  collectMarkdownDir(agentsDir, 'subagents', ['name', 'description'], out);
  collectMarkdownDir(agentsDir, 'commands', ['description'], out);
  collectHooks(agentsDir, out);
  collectTypes(agentsDir, meta, out);
  out.set(`${PLUGIN_DIR}/.mcp.json`, json({ mcpServers: { [MCP_SERVER_NAME]: mcpServer(meta) } }));
  out.set(`${PLUGIN_DIR}/${MCP_LAUNCHER}`, LAUNCHER_SOURCE);
  out.set(`${PLUGIN_DIR}/GENERATED.md`, `# Generated plugin\n\n${GENERATED_NOTE}\n`);
  out.set(
    MARKETPLACE_PATH,
    json({
      name: meta.name,
      description: meta.description,
      owner: meta.author,
      plugins: [
        { name: meta.name, source: `./${PLUGIN_DIR}`, description: meta.description, version: meta.version },
      ],
    }),
  );
  return new Map([...out].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
}

/** Compares the expected tree with what is on disk under `root`; returns human-readable problems. */
export function findStaleFiles(root, expected) {
  const problems = [];
  for (const [path, content] of expected) {
    const absolute = join(root, path);
    if (!existsSync(absolute)) problems.push(`missing: ${path}`);
    else if (readText(absolute) !== content) problems.push(`out of date: ${path}`);
  }
  const pluginRoot = join(root, PLUGIN_DIR);
  if (existsSync(pluginRoot)) {
    for (const file of listFiles(pluginRoot)) {
      if (!expected.has(`${PLUGIN_DIR}/${file}`)) problems.push(`unexpected: ${PLUGIN_DIR}/${file}`);
    }
  }
  return problems;
}

/** Replaces the generated tree under `root` with `expected`. */
export function writePlugin(root, expected) {
  rmSync(join(root, PLUGIN_DIR), { recursive: true, force: true });
  for (const [path, content] of expected) {
    const absolute = join(root, path);
    mkdirSync(dirname(absolute), { recursive: true });
    writeFileSync(absolute, content, 'utf8');
  }
}
